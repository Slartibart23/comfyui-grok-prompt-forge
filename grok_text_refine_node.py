"""
Grok Prompt Forge — ComfyUI custom nodes
Prompt generation, text refinement and vision captioning via the official
xAI Grok API (OpenAI-compatible).

v3.0.0: the new `Grok Prompt Forge (xAI)` node (grok_forge/forge_node.py)
combines text refinement and vision captioning with task presets. The two
older API nodes below stay registered as "legacy" so existing workflows keep
loading and running; they are hidden from the node search.

v2.0.1: if a model rejects a sampling parameter (e.g. presencePenalty on
reasoning models), the offending parameter is stripped and the request is
automatically resent instead of failing the queue.

v2.0.0: adds top_p, presence_penalty and frequency_penalty to both API nodes
(neutral values are omitted from the request for reasoning-model
compatibility) and layman-friendly tooltips on every widget. Node class IDs
are unchanged — existing workflows keep working.

API key resolution order:
    1. `api_key` widget (not recommended — ends up in workflow exports)
    2. Environment variable XAI_API_KEY
    3. Key file (default: grok_api_key.txt in the ComfyUI root directory)

License: MIT
"""

