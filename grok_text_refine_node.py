    def refine(self, text, system_prompt, model, temperature, max_tokens,
               top_p=1.0, presence_penalty=0.0, frequency_penalty=0.0,
               seed=0, api_key="", api_key_file="grok_api_key.txt",
               base_url="https://api.x.ai/v1", fallback_to_input=True,
               timeout_seconds=120):

        if not text or not text.strip():
            print("[Grok Text Refine] Empty input text — passing through.")
            return (text or "",)

        try:
            key = _resolve_api_key(api_key, api_key_file)
        except RuntimeError as e:
            if fallback_to_input:
                print(str(e) + " — falling back to input text.")
                return (text,)
            raise

        url = base_url.rstrip("/") + "/chat/completions"
        payload = {
            "model": model.strip(),
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": text},
            ],
            "temperature": float(temperature),
            "max_tokens": int(max_tokens),
        }
        # Neutral values are omitted entirely: identical behavior to older
        # versions, and reasoning models that reject these params stay happy.
        _apply_sampling_params(payload, top_p, presence_penalty,
                               frequency_penalty)
        headers = {
            "Authorization": f"Bearer {key}",
            "Content-Type": "application/json",
        }

        last_error = None
        attempt = 0
        while attempt < 3:  # 1 try + 2 retries on transient errors
            try:
                resp = requests.post(url, json=payload, headers=headers,
                                     timeout=timeout_seconds)
                if resp.status_code == 400:
                    # Some models reject sampling params (e.g. presencePenalty
                    # on reasoning models). Strip the offender and resend —
                    # doesn't consume a retry attempt.
                    removed = _strip_unsupported_param(payload, resp.text)
                    if removed:
                        print(f"[Grok Text Refine] Model '{payload['model']}' "
                              f"rejected '{removed}' — retrying without it.")
                        continue
                if resp.status_code in (429, 500, 502, 503, 504):
                    last_error = RuntimeError(
                        f"[Grok Text Refine] HTTP {resp.status_code}: {resp.text[:300]}"
                    )
                    attempt += 1
                    time.sleep(2 * attempt)
                    continue
                if resp.status_code != 200:
                    raise RuntimeError(
                        f"[Grok Text Refine] HTTP {resp.status_code}: {resp.text[:500]}"
                    )

                data = resp.json()
                choices = data.get("choices") or []
                if not choices:
                    raise RuntimeError(f"[Grok Text Refine] Empty response: {str(data)[:500]}")
                content = (choices[0].get("message") or {}).get("content") or ""
                refined = _strip_wrapping(content)

                if not refined:
                    raise RuntimeError("[Grok Text Refine] Model returned empty text.")

                usage = data.get("usage") or {}
                print(f"[Grok Text Refine] OK (model={payload['model']}, "
                      f"tokens={usage.get('total_tokens', '?')}).")
                return (refined,)

            except (requests.Timeout, requests.ConnectionError) as e:
                last_error = e
                attempt += 1
                time.sleep(2 * attempt)
                continue

        # All attempts failed
        msg = f"[Grok Text Refine] Request failed after retries: {last_error}"
        if fallback_to_input:
            print(msg + " — falling back to input text.")
            return (text,)
        raise RuntimeError(msg)


