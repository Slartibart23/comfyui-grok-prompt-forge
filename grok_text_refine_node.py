    @staticmethod
    def _image_to_data_uri(image, image_index=0, max_side=1536, image_format="jpeg"):
        import base64
        import io

        import numpy as np
        from PIL import Image

        arr = image
        if hasattr(arr, "cpu"):  # torch tensor from ComfyUI
            arr = arr.cpu().numpy()
        arr = np.asarray(arr)
        if arr.ndim == 4:  # (B, H, W, C) — pick one image from the batch
            idx = min(int(image_index), arr.shape[0] - 1)
            arr = arr[idx]
        arr = np.clip(arr * 255.0, 0, 255).astype(np.uint8)

        img = Image.fromarray(arr)
        if max(img.size) > max_side:
            img.thumbnail((max_side, max_side), Image.LANCZOS)

        buf = io.BytesIO()
        if image_format == "png":
            img.save(buf, format="PNG")
            mime = "image/png"
        else:
            img.convert("RGB").save(buf, format="JPEG", quality=92)
            mime = "image/jpeg"
        b64 = base64.b64encode(buf.getvalue()).decode("ascii")
        return f"data:{mime};base64,{b64}"

